from pathlib import Path
from typing import Iterator, override

from ..data_source import Split
from .sft_data_source import SFTDataSource, SftExample

SFT_DIR = Path(__file__).parent
TRAIN_FILENAME = "reverse-train.txt"
# The directory of the validation slices: one file per subtask, the file's name (without .txt) being its name. See reverse_gen.py.
SLICES_DIRNAME = "reverse-validation-slices"

def _parse_examples(text: str, path: Path) -> Iterator[SftExample]:
    """The examples in the text of a file, one `<string>\\t<reversed string>` per line. Raises, naming the line, if one is malformed or isn't a reversal."""
    if not text:
        return
    for line_number, line in enumerate(text.removesuffix("\n").split("\n"), start=1):
        parts = line.split("\t")
        if len(parts) != 2:
            raise ValueError(f"{path}:{line_number}: expected '<string>\\t<reversed string>', got {line!r}")
        string, reversed_string = parts
        if reversed_string != string[::-1]:
            raise ValueError(f"{path}:{line_number}: {reversed_string!r} is not the reverse of {string!r}")
        yield SftExample(input=string, output=reversed_string)

class ReverseSource(SFTDataSource):
    """
    SFTDataSource for the string reversal examples generated by reverse_gen.py.
    The train split is one file. The validation split is the pool of the validation slices (see get_validation_slices), so that the loss on it
    is an even mix of the subtasks.
    """

    name = "reverse"

    @override
    def iter_examples(self, split: Split) -> Iterator[SftExample]:
        if split == "validation":
            for examples in self.get_validation_slices().values():
                yield from examples
            return
        path = SFT_DIR / TRAIN_FILENAME
        yield from _parse_examples(path.read_text(encoding="utf-8"), path)

    @override
    def get_validation_slices(self) -> dict[str, list[SftExample]]:
        """
        Returns a dict of slice name (the file name, e.g. "repeated_char") to the examples of that slice. Sorted by name.
        """
        slices_dir = SFT_DIR / SLICES_DIRNAME
        if not slices_dir.is_dir():
            raise FileNotFoundError(f"no validation slices at {slices_dir}; make them with `python -m src.tiny_shakespeare.data.sft.reverse_gen`")
        slices: dict[str, list[SftExample]] = {}
        for path in sorted(slices_dir.glob("*.txt")):
            examples = list(_parse_examples(path.read_text(encoding="utf-8"), path))
            if not examples:
                raise ValueError(f"{path} has no examples, so its slice can't be scored")
            slices[path.stem] = examples
        if not slices:
            raise ValueError(f"{slices_dir} has no slice files (<name>.txt)")
        return slices
